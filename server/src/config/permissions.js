// Central Role-Based Access Control (RBAC) Permissions Matrix

export const ROLES = {
  ADMIN: 'admin',
  STUDENT: 'student'
};

export const PERMISSIONS = {
  // Profiles
  READ_OWN_PROFILE: [ROLES.STUDENT, ROLES.ADMIN],
  UPDATE_OWN_PROFILE: [ROLES.STUDENT, ROLES.ADMIN],
  READ_ANY_PROFILE: [ROLES.ADMIN],
  UPDATE_ANY_PROFILE: [ROLES.ADMIN],
  DELETE_ANY_PROFILE: [ROLES.ADMIN],

  // DSA
  CRUD_OWN_DSA: [ROLES.STUDENT, ROLES.ADMIN],
  CRUD_ANY_DSA: [ROLES.ADMIN],
  MANAGE_DSA_SHEET: [ROLES.ADMIN],

  // Tests & Aptitude
  TAKE_TESTS: [ROLES.STUDENT, ROLES.ADMIN],
  READ_OWN_TEST_HISTORY: [ROLES.STUDENT, ROLES.ADMIN],
  MANAGE_TESTS_AND_QUESTIONS: [ROLES.ADMIN],
  DELETE_ANY_TEST_ATTEMPT: [ROLES.ADMIN],

  // Resumes
  CRUD_OWN_RESUME: [ROLES.STUDENT, ROLES.ADMIN],
  READ_ANY_RESUME: [ROLES.ADMIN],
  DELETE_ANY_RESUME: [ROLES.ADMIN],

  // Mock Interviews
  TAKE_INTERVIEW: [ROLES.STUDENT, ROLES.ADMIN],
  READ_OWN_INTERVIEW: [ROLES.STUDENT, ROLES.ADMIN],
  MANAGE_ANY_INTERVIEW: [ROLES.ADMIN],

  // Placement Drives & Shortlists
  READ_DRIVES: [ROLES.STUDENT, ROLES.ADMIN],
  MANAGE_DRIVES: [ROLES.ADMIN],
  MANAGE_SHORTLISTS: [ROLES.ADMIN],

  // Scoring Weights & Admin Analytics
  MANAGE_WEIGHTS: [ROLES.ADMIN],
  READ_AUDIT_LOG: [ROLES.ADMIN],
  MANAGE_USERS: [ROLES.ADMIN],
  MANAGE_MESSAGES: [ROLES.ADMIN],
  SEND_ANNOUNCEMENTS: [ROLES.ADMIN]
};

export const can = (role, permission) => {
  const allowed = PERMISSIONS[permission];
  return Boolean(allowed && allowed.includes(role));
};
